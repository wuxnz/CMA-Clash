	<h1>Roadmap</h1>

	<p>
		Everything that is planned is tracked on the
		<a href="https://github.com/wuxnz/CMA-Clash/issues">project issue tracker</a>. Want
		something on this list? Open an issue and tell us about it.
	</p>

	<h2>Shipped</h2>
	<ul>
		<li><input type="checkbox" checked disabled /> Live quizzes with PIN and QR lobbies</li>
		<li><input type="checkbox" checked disabled /> Battle mode and matchmaking</li>
		<li><input type="checkbox" checked disabled /> Timed practice mode</li>
		<li><input type="checkbox" checked disabled /> XP, levels and streaks</li>
		<li><input type="checkbox" checked disabled /> Weekly and all-time leaderboards</li>
		<li>
			<input type="checkbox" checked disabled /> Seeded CCMA, EKG, phlebotomy, CPR/BLS and clinical
			skills question banks
		</li>
		<li><input type="checkbox" checked disabled /> Study guides by topic</li>
		<li><input type="checkbox" checked disabled /> Quiz import from Kahoot, .cqa and Excel</li>
		<li><input type="checkbox" checked disabled /> Public quiz discovery</li>
		<li>
			<input type="checkbox" checked disabled /> User-management, password-reset and session-management
		</li>
		<li><input type="checkbox" checked disabled /> Moderation queue</li>
		<li><input type="checkbox" checked disabled /> Hardware quiz controller support</li>
		<li><input type="checkbox" checked disabled /> Self-hosting with Docker Compose</li>
	</ul>

	<h2>What's next</h2>
	<p>
		Planned work is sorted by label:
		<a href="https://github.com/wuxnz/CMA-Clash/labels/enhancement">enhancement</a> for new
		features and
		<a href="https://github.com/wuxnz/CMA-Clash/labels/good%20first%20issue">good first issue</a
		>
		for contributions that are ready to be picked up.
	</p>
